import fs from "fs/promises"
import path from "path"
import { fileURLToPath } from "url"

// Emulate __dirname in ESM
const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const REGISTRY_PATH = path.join(__dirname, "../registry.json")
const OUTPUT_DIR = path.join(__dirname, "../__registry__")
const OUTPUT_FILE = path.join(OUTPUT_DIR, "index.tsx")

async function buildRegistry() {
  try {
    console.log("⏳ Building Satis UI internal registry...")

    // 1. Ensure the __registry__ directory exists
    await fs.mkdir(OUTPUT_DIR, { recursive: true })

    // 2. Read the master registry.json
    const registryData = JSON.parse(await fs.readFile(REGISTRY_PATH, "utf8"))

    // 3. Start building the TypeScript file content
    let indexContent = `// @ts-nocheck
// This file is autogenerated by scripts/build-registry.mjs
// Do not edit this file directly.
import dynamic from "next/dynamic";

export const Index: Record<string, any> = {
`

    // 4. Loop through every item in the registry
    for (const item of registryData.items) {
      // Find the main file path (usually the first file in the array)
      const mainFile = item.files[0]
      if (!mainFile) continue

      const filePath = path.join(__dirname, "..", mainFile.path)

      // Read the physical file content
      let rawContent = ""
      try {
        rawContent = await fs.readFile(filePath, "utf8")
      } catch (err) {
        console.warn(`⚠️ Warning: Could not find file ${filePath}`)
        continue
      }

      // We must rigorously escape the raw string so it doesn't break the JS template literal
      const escapedRaw = rawContent
        .replace(/\\/g, "\\\\") // Escape backslashes
        .replace(/`/g, "\\`") // Escape backticks
        .replace(/\$/g, "\\$") // Escape template literal injections

      // Clean the path for the Next.js dynamic import (remove .tsx extension)
      const importPath = mainFile.path.replace(/\.tsx?$/, "")

      // Append the object to our index dictionary
      indexContent += `  "${item.name}": {
    name: "${item.name}",
    type: "${item.type}",
    registryDependencies: ${JSON.stringify(item.registryDependencies || [])},
    component: dynamic(() => import("@/${importPath}")),
    raw: \`${escapedRaw}\`,
  },
`
    }

    // 5. Close the object map
    indexContent += `};
`

    // 6. Write the file to disk
    await fs.writeFile(OUTPUT_FILE, indexContent, "utf8")
    console.log("✅ Registry successfully generated at __registry__/index.tsx")
  } catch (error) {
    console.error("❌ Failed to build registry:", error)
    process.exit(1)
  }
}

buildRegistry()
